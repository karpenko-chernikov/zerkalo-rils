def загрузить_настройки() -> dict:
    if not ФАЙЛ_НАСТРОЕК.exists():
        raise Ошибка(f"Нет файла настроек: {ФАЙЛ_НАСТРОЕК}")
    данные = json.loads(ФАЙЛ_НАСТРОЕК.read_text(encoding="utf-8"))
    настройки = dict(УМОЛЧАНИЕ)
    настройки.update(данные)
    круг = dict(УМОЛЧАНИЕ["круг"])
    круг.update(данные.get("круг") or {})
    настройки["круг"] = круг
    ширина = int(настройки["ширина"])
    высота = int(настройки["высота"])
    if ширина % 2 or высота % 2 or ширина < 2 or высота < 2:
        raise Ошибка("Ширина и высота кадра должны быть чётными и больше нуля.")
    if float(круг["радиус"]) <= 1:
        raise Ошибка("Радиус круга в настройках должен быть больше 1.")
    if int(настройки["ударов_на_фото"]) < 1:
        raise Ошибка("«ударов_на_фото» должно быть не меньше 1.")
    if int(настройки["кадров_в_секунду"]) < 1:
        raise Ошибка("«кадров_в_секунду» должно быть не меньше 1.")
    настройки["ширина"] = ширина
    настройки["высота"] = высота
    return настройки



def проявить(кадр: np.ndarray, резкость: float = 0.6, ясность: float = 0.18) -> np.ndarray:
    """Чуть сочнее и заметно резче, без молочной дымки. Круг и геометрия не меняются."""
    лаб = cv2.cvtColor(кадр, cv2.COLOR_BGR2LAB).astype(np.float32)
    свет = лаб[:, :, 0]
    if ясность > 0:
        широкое = cv2.GaussianBlur(свет, (0, 0), 14)
        свет = свет + ясность * (свет - широкое)
    мелко = cv2.GaussianBlur(свет, (0, 0), 0.65)
    свет = свет + резкость * (свет - мелко)
    свет = (свет - 128.0) * 1.05 + 128.0
    лаб[:, :, 0] = np.clip(свет, 0, 255)
    насыщенность = np.hypot(лаб[:, :, 1] - 128.0, лаб[:, :, 2] - 128.0)
    # Блеклые места усиливаются сильнее, уже яркие цвета — скромнее.
    сила = 1.10 + 0.18 * (1.0 - np.clip(насыщенность / 70.0, 0.0, 1.0))
    for канал in (1, 2):
        лаб[:, :, канал] = np.clip((лаб[:, :, канал] - 128.0) * сила + 128.0, 0, 255)
    return cv2.cvtColor(лаб.astype(np.uint8), cv2.COLOR_LAB2BGR)


def залить_дыры(резкий: np.ndarray, маска: np.ndarray) -> np.ndarray:
    """Тянет цвет фото в пустые углы, чтобы размытие не тащило за собой чёрную кайму."""
    цвет = резкий.astype(np.float32)
    вес = (маска > 0).astype(np.float32)
    if float(вес.min()) == 1.0:
        return резкий
    for сигма in (14.0, 32.0, 70.0, 140.0):
        размытый_цвет = cv2.GaussianBlur(цвет * вес[..., None], (0, 0), сигма)
        размытый_вес = cv2.GaussianBlur(вес, (0, 0), сигма)
        можно = размытый_вес > 0.02
        подставить = можно & (вес < 0.5)
        цвет[подставить] = размытый_цвет[подставить] / размытый_вес[подставить, None]
        вес = np.maximum(вес, можно.astype(np.float32))
    return np.clip(цвет, 0, 255).astype(np.uint8)


def кадр_с_резким_кругом(резкий: np.ndarray, маска: np.ndarray, настройки: dict, сигма: float = 28.0) -> np.ndarray:
    """Круг остаётся резким. Всё, что снаружи, сильно размыто."""
    залитый = залить_дыры(резкий, маска)
    фон = cv2.GaussianBlur(залитый, (0, 0), сигма)
    цель = настройки["круг"]
    высота, ширина = резкий.shape[:2]
    сетка_y, сетка_x = np.mgrid[0:высота, 0:ширина]
    от_круга = np.hypot(сетка_x - float(цель["центр_x"]), сетка_y - float(цель["центр_y"]))
    радиус = float(цель["радиус"])
    альфа = плавный((радиус + 6.0 - от_круга) / 22.0)
    альфа *= маска.astype(np.float32) / 255.0
    итог = резкий.astype(np.float32) * альфа[..., None] + фон.astype(np.float32) * (1.0 - альфа[..., None])
    return np.clip(итог, 0, 255).astype(np.uint8)


def кадры_на_радиус(отобранные: list[tuple[Path, dict]], настройки: dict, сколько: int) -> tuple[float, list[tuple[Path, dict]], list[str]]:
    """Общий радиус, при котором ровно `сколько` фото закрывают кадр. Остальные — в стороне."""
    с_запасом = []
    for путь, запись in отобранные:
        нужный = радиус_чтобы_закрыть(
            float(запись["центр_x"]),
            float(запись["центр_y"]),
            float(запись["радиус"]),
            float(запись["ширина"]),
            float(запись["высота"]),
            настройки,
        )
        с_запасом.append((нужный, путь, запись))
    с_запасом.sort(key=lambda строка: строка[0])
    сколько = min(сколько, len(с_запасом))
    порог = с_запасом[сколько - 1][0]
    радиус = порог + 1.0
    имена = {путь.name for _, путь, _ in с_запасом[:сколько]}
    выбранные = [(путь, запись) for путь, запись in отобранные if путь.name in имена]
    мимо = [путь.name for _, путь, _ in с_запасом[сколько:]]
    return радиус, выбранные, мимо


def записать_кадр(папка: Path, имя: str, кадр: np.ndarray, качество: int = 95, плотный_цвет: bool = False) -> None:
    папка.mkdir(parents=True, exist_ok=True)
    параметры = [int(cv2.IMWRITE_JPEG_QUALITY), качество]
    if плотный_цвет:
        параметры += [int(cv2.IMWRITE_JPEG_SAMPLING_FACTOR), int(cv2.IMWRITE_JPEG_SAMPLING_FACTOR_444)]
    cv2.imwrite(str(папка / имя), кадр, параметры)


def очистить_кадры(папка: Path) -> None:
    if not папка.exists():
        return
    for старый in папка.glob("*.jpg"):
        старый.unlink()


def кадр_с_рамкой(резкий: np.ndarray, маска: np.ndarray) -> np.ndarray:
    фон = np.full_like(резкий, ЦВЕТ_РАМКИ)
    альфа = cv2.GaussianBlur(маска, (0, 0), 0.6).astype(np.float32) / 255.0
    итог = резкий.astype(np.float32) * альфа[..., None] + фон.astype(np.float32) * (1.0 - альфа[..., None])
    return np.clip(итог, 0, 255).astype(np.uint8)


class Дорисовщик:
    """LaMa: дорисовывает только пустые края, само фото не переписывает."""

    АДРЕС = "https://github.com/enesmsahin/simple-lama-inpainting/releases/download/v0.1.0/big-lama.pt"

    def __init__(self) -> None:
        import torch

        папка = КОРЕНЬ / "модели"
        папка.mkdir(exist_ok=True)
        путь = папка / "big-lama.pt"
        if not путь.exists() or путь.stat().st_size < 1_000_000:
            print("Скачиваю модель дорисовки, один раз, около 200 МБ.")
            torch.hub.download_url_to_file(self.АДРЕС, str(путь), progress=True)
        self.torch = torch
        варианты = []
        if torch.backends.mps.is_available():
            варианты.append(torch.device("mps"))
        варианты.append(torch.device("cpu"))
        ошибка_загрузки: Exception | None = None
        for устройство in варианты:
            try:
                self.модель = torch.jit.load(str(путь), map_location=устройство)
                self.модель.eval()
                self.устройство = устройство
                ошибка_загрузки = None
                break
            except Exception as ошибка:
                ошибка_загрузки = ошибка
        if ошибка_загрузки is not None:
            raise ошибка_загрузки

    def __call__(self, rgb: np.ndarray, дыра: np.ndarray) -> np.ndarray:
        torch = self.torch
        высота, ширина = rgb.shape[:2]
        дополнение_y = (8 - высота % 8) % 8
        дополнение_x = (8 - ширина % 8) % 8
        if дополнение_y or дополнение_x:
            rgb = np.pad(rgb, ((0, дополнение_y), (0, дополнение_x), (0, 0)), mode="symmetric")
            дыра = np.pad(дыра, ((0, дополнение_y), (0, дополнение_x)), mode="symmetric")
        изображение = torch.from_numpy(np.transpose(rgb.astype(np.float32) / 255.0, (2, 0, 1))).unsqueeze(0)
        маска = torch.from_numpy((дыра.astype(np.float32) / 255.0)[None, ...]).unsqueeze(0)
        изображение = изображение.to(self.устройство)
        маска = (маска.to(self.устройство) > 0).float()
        with torch.inference_mode():
            ответ = self.модель(изображение, маска)
        картинка = ответ[0].permute(1, 2, 0).detach().float().cpu().numpy()
        картинка = np.clip(картинка * 255.0, 0, 255).astype(np.uint8)
        return картинка[:высота, :ширина]


def дорисовать(резкий: np.ndarray, маска: np.ndarray, лама: Дорисовщик, настройки: dict) -> np.ndarray:
    if int(маска.min()) == 255:
        return резкий
    # На полном кадре модель сыпет шум в большую дыру. На стороне около 720
    # она продолжает небо и пол, а само фото потом возвращается резким.
    высота, ширина = резкий.shape[:2]
    масштаб = min(1.0, 720.0 / max(высота, ширина))
    новая_ширина = max(8, int(round(ширина * масштаб)) // 8 * 8)
    новая_высота = max(8, int(round(высота * масштаб)) // 8 * 8)
    маленькое = cv2.resize(резкий, (новая_ширина, новая_высота), interpolation=cv2.INTER_AREA)
    дыра = cv2.bitwise_not(маска)
    дыра = cv2.dilate(дыра, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (9, 9)))
    маленькая_дыра = cv2.resize(дыра, (новая_ширина, новая_высота), interpolation=cv2.INTER_NEAREST)
    rgb = cv2.cvtColor(маленькое, cv2.COLOR_BGR2RGB)
    готово = cv2.cvtColor(лама(rgb, маленькая_дыра), cv2.COLOR_RGB2BGR)
    готово = cv2.resize(готово, (ширина, высота), interpolation=cv2.INTER_CUBIC)
    альфа = cv2.GaussianBlur(маска, (0, 0), 10).astype(np.float32) / 255.0
    цель = настройки["круг"]
    высота, ширина = резкий.shape[:2]
    сетка_y, сетка_x = np.mgrid[0:высота, 0:ширина]
    от_круга = np.hypot(сетка_x - float(цель["центр_x"]), сетка_y - float(цель["центр_y"]))
    внутри_круга = (от_круга <= float(цель["радиус"]) + 8.0) & (маска > 0)
    альфа = np.maximum(альфа, внутри_круга.astype(np.float32))
    итог = резкий.astype(np.float32) * альфа[..., None] + готово.astype(np.float32) * (1.0 - альфа[..., None])
    return np.clip(итог, 0, 255).astype(np.uint8)



def в_srgb(снимок: Image.Image, профиль: bytes | None) -> Image.Image:
    """С айфона приходит Display P3. Без перевода цвета на экране тусклее, чем в телефоне."""
    if снимок.mode != "RGB":
        снимок = снимок.convert("RGB")
    if not профиль:
        return снимок
    try:
        источник = ImageCms.ImageCmsProfile(BytesIO(профиль))
        return ImageCms.profileToProfile(
            снимок,
            источник,
            ImageCms.createProfile("sRGB"),
            outputMode="RGB",
            renderingIntent=ImageCms.Intent.RELATIVE_COLORIMETRIC,
        )
    except (ImageCms.PyCMSError, OSError, ValueError):
        return снимок


def открыть_фото(путь: Path) -> np.ndarray:
    if путь.suffix.lower() in {".heic", ".heif"} and not HEIC_ДОСТУПЕН:
        raise Ошибка("Чтобы открывать HEIC с айфона, установи пакеты: pip install pillow-heif")
    with Image.open(путь) as исходник:
        профиль = исходник.info.get("icc_profile")
        снимок = ImageOps.exif_transpose(исходник)
        снимок = в_srgb(снимок, профиль)
        массив = np.array(снимок)
    return cv2.cvtColor(массив, cv2.COLOR_RGB2BGR)



def список_фото() -> list[Path]:
    if not ПАПКА_ФОТО.exists():
        raise Ошибка(f"Нет папки {ПАПКА_ФОТО}")
    все = [путь for путь in ПАПКА_ФОТО.iterdir() if путь.is_file() and путь.suffix.lower() in РАСШИРЕНИЯ_ФОТО]
    все.sort(key=lambda путь: путь.name.lower())
    порядок = ПАПКА_ФОТО / "порядок.txt"
    if not порядок.exists():
        return все
    по_имени = {путь.name: путь for путь in все}
    выбранные = []
    неизвестные = []
    for строка in порядок.read_text(encoding="utf-8-sig").splitlines():
        имя = строка.strip()
        if not имя or имя.startswith("#"):
            continue
        if имя in по_имени:
            выбранные.append(по_имени[имя])
        else:
            неизвестные.append(имя)
    if неизвестные:
        print("В порядок.txt нет таких файлов: " + ", ".join(неизвестные))
    лишние = [путь.name for путь in все if путь not in выбранные]
    if лишние:
        print(f"Не перечислены в порядок.txt, поэтому не беру: {len(лишние)}")
    return выбранные



def команда_собрать(только_кадры: bool, темп_из_команды: float | None) -> None:
    настройки = загрузить_настройки()
    кадры = кадры_отбора()
    print(f"Беру кадры из «варианты/отбор»: {len(кадры)}")
    if только_кадры:
        print(f"Картинки уже лежат в {ПАПКА_ВАРИАНТОВ / 'отбор'}")
        return

    нужен_ffmpeg()
    трек = найти_музыку()
    вся_длина = длительность_аудио(трек)
    начало = max(0.0, float(настройки["начало_секунды"]))
